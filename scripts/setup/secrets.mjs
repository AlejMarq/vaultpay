// Per-process secret files (data/secrets/<process>.env), generated independently on each
// computer. Each process loads only its own file (process.loadEnvFile), so a process
// never holds another process's private keys.
//
// Keys:
//   service token  – Ed25519, used with jose (D10). Identity (inside the Next.js "web"
//                    process) holds the signing key; services hold the public key.
//   risk decision  – Ed25519. Only Fraud & Risk Check signs; Settlement verifies (82).
// Paths to certificates are relative to data/.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import util from 'node:util';

import { writeNewFile } from './paths.mjs';

const tls = (name) => ({ TLS_CERT: `pki/${name}.crt`, TLS_KEY: `pki/${name}.key`, TLS_CA: 'pki/ca.crt' });

// Which settings each process receives. Values are filled from generated material.
const SPEC = {
  web: (m) => ({
    BETTER_AUTH_SECRET: m.betterAuthSecret,
    BETTER_AUTH_URL: 'http://localhost:3000',
    SERVICE_TOKEN_SIGNING_KEY: m.token.privateKey,
    SERVICE_TOKEN_KEY_ID: m.token.keyId,
    // Reconciliation & Audit runs inside Next.js and reaches CBI with a read-only client cert
    RECON_TLS_CERT: 'pki/recon.crt',
    RECON_TLS_KEY: 'pki/recon.key',
    TLS_CA: 'pki/ca.crt',
  }),
  fraud: (m) => ({
    RISK_DECISION_SIGNING_KEY: m.risk.privateKey,
    RISK_DECISION_KEY_ID: m.risk.keyId,
    SERVICE_TOKEN_PUBLIC_KEY: m.token.publicKey,
    SERVICE_TOKEN_KEY_ID: m.token.keyId,
    MOCK_FRAUD_SCORING_API_KEY: m.fraudScoringApiKey,
  }),
  settlement: (m) => ({
    RISK_DECISION_PUBLIC_KEY: m.risk.publicKey,
    RISK_DECISION_KEY_ID: m.risk.keyId,
    SERVICE_TOKEN_PUBLIC_KEY: m.token.publicKey,
    SERVICE_TOKEN_KEY_ID: m.token.keyId,
    ...tls('settlement'),
  }),
  cbi: (m) => ({
    SERVICE_TOKEN_PUBLIC_KEY: m.token.publicKey,
    SERVICE_TOKEN_KEY_ID: m.token.keyId,
    MOCK_CORE_BANKING_API_KEY: m.coreBankingApiKey,
    ...tls('cbi'),
  }),
  'mock-core-banking': (m) => ({
    MOCK_CORE_BANKING_API_KEY: m.coreBankingApiKey,
    ...tls('mock-core-banking'),
  }),
  'mock-fraud-scoring': (m) => ({
    MOCK_FRAUD_SCORING_API_KEY: m.fraudScoringApiKey,
  }),
};

export const PROCESSES = Object.freeze(Object.keys(SPEC));
export const SECRET_FILES = Object.freeze(PROCESSES.map((p) => `${p}.env`).sort());

const b64 = (buf) => buf.toString('base64url');
const randomSecret = () => b64(crypto.randomBytes(32));

function keyIdFor(prefix, spkiDer) {
  return `${prefix}-${crypto.createHash('sha256').update(spkiDer).digest('hex').slice(0, 16)}`;
}

function ed25519(prefix) {
  const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
  const spki = publicKey.export({ type: 'spki', format: 'der' });
  return {
    privateKey: b64(privateKey.export({ type: 'pkcs8', format: 'der' })),
    publicKey: b64(spki),
    keyId: keyIdFor(prefix, spki),
  };
}

export function generateSecrets(dir, { now = Date.now() } = {}) {
  const material = {
    betterAuthSecret: randomSecret(),
    token: ed25519('st'),
    risk: ed25519('rd'),
    coreBankingApiKey: randomSecret(),
    fraudScoringApiKey: randomSecret(),
  };
  for (const proc of PROCESSES) {
    const values = { VAULTPAY_PROCESS: proc, ...SPEC[proc](material) };
    const body = Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n');
    writeNewFile(path.join(dir, `${proc}.env`), [
      `# VaultPay ${proc} – generated by npm run setup on ${new Date(now).toISOString()}`,
      '# Local development secrets for THIS computer only. Never commit or copy.',
      body,
      '',
    ].join('\n'));
  }
}

// Loading helpers (also used by the services later).
export const loadPrivateKey = (value) => crypto.createPrivateKey({ key: Buffer.from(value, 'base64url'), format: 'der', type: 'pkcs8' });
export const loadPublicKey = (value) => crypto.createPublicKey({ key: Buffer.from(value, 'base64url'), format: 'der', type: 'spki' });

/**
 * Validates every secret file: exact set of files, exact set of keys per process,
 * keys that load, matching key pairs and key IDs across processes, shared API keys
 * that agree, and certificate paths that stay inside data/pki.
 */
export function verifySecrets(dir) {
  const problems = [];
  let present;
  try {
    present = fs.readdirSync(dir).sort();
  } catch (err) {
    return { problems: [`secrets directory unreadable (${err.code})`], keyIds: {} };
  }
  const missing = SECRET_FILES.filter((f) => !present.includes(f));
  const extra = present.filter((f) => !SECRET_FILES.includes(f));
  if (missing.length) problems.push(`missing: ${missing.join(', ')}`);
  if (extra.length) problems.push(`unexpected files: ${extra.join(', ')}`);
  if (missing.length) return { problems, keyIds: {} };

  // Compare each file's keys against what a fresh generation would produce.
  const placeholder = { token: {}, risk: {} };
  const shape = (proc) => ['VAULTPAY_PROCESS', ...Object.keys(SPEC[proc](placeholder))].sort();
  const env = {};
  for (const proc of PROCESSES) {
    const values = util.parseEnv(fs.readFileSync(path.join(dir, `${proc}.env`), 'utf8'));
    env[proc] = values;
    const keys = Object.keys(values).sort();
    const want = shape(proc);
    const lacking = want.filter((k) => !keys.includes(k));
    const surplus = keys.filter((k) => !want.includes(k));
    if (lacking.length) problems.push(`${proc}.env: missing ${lacking.join(', ')}`);
    if (surplus.length) problems.push(`${proc}.env: must not contain ${surplus.join(', ')}`);
    if (values.VAULTPAY_PROCESS !== proc) problems.push(`${proc}.env: VAULTPAY_PROCESS is "${values.VAULTPAY_PROCESS}"`);
    for (const [k, v] of Object.entries(values)) {
      if (/_TLS_(CERT|KEY)$|^TLS_(CERT|KEY|CA)$/.test(k) && !/^pki\/[a-z-]+\.(crt|key)$/.test(v)) {
        problems.push(`${proc}.env: ${k} must point inside data/pki (got "${v}")`);
      }
    }
  }
  if (problems.length) return { problems, keyIds: {} };

  const pair = (label, signer, signerKey, keyIdName, verifiers, publicName, prefix) => {
    let publicDer;
    try {
      const priv = loadPrivateKey(env[signer][signerKey]);
      if (priv.asymmetricKeyType !== 'ed25519') throw new Error(`is ${priv.asymmetricKeyType}, expected ed25519`);
      publicDer = crypto.createPublicKey(priv).export({ type: 'spki', format: 'der' });
    } catch (err) {
      problems.push(`${signer}.env: ${signerKey} does not load (${err.message})`);
      return undefined;
    }
    const keyId = keyIdFor(prefix, publicDer);
    if (env[signer][keyIdName] !== keyId) problems.push(`${signer}.env: ${keyIdName} does not match its ${label} key`);
    for (const proc of verifiers) {
      try {
        const pub = loadPublicKey(env[proc][publicName]);
        if (!pub.export({ type: 'spki', format: 'der' }).equals(publicDer)) problems.push(`${proc}.env: ${publicName} does not match ${signer}'s ${label} signing key`);
      } catch (err) {
        problems.push(`${proc}.env: ${publicName} does not load (${err.message})`);
      }
      if (env[proc][keyIdName] !== keyId) problems.push(`${proc}.env: ${keyIdName} does not match ${signer}'s ${label} key`);
    }
    return keyId;
  };
  const tokenKeyId = pair('service token', 'web', 'SERVICE_TOKEN_SIGNING_KEY', 'SERVICE_TOKEN_KEY_ID', ['fraud', 'settlement', 'cbi'], 'SERVICE_TOKEN_PUBLIC_KEY', 'st');
  const riskKeyId = pair('risk decision', 'fraud', 'RISK_DECISION_SIGNING_KEY', 'RISK_DECISION_KEY_ID', ['settlement'], 'RISK_DECISION_PUBLIC_KEY', 'rd');

  const strong = (label, value) => {
    if (typeof value !== 'string' || Buffer.from(value, 'base64url').length < 32) problems.push(`${label} must be at least 32 random bytes`);
  };
  strong('web.env: BETTER_AUTH_SECRET', env.web.BETTER_AUTH_SECRET);
  strong('cbi.env: MOCK_CORE_BANKING_API_KEY', env.cbi.MOCK_CORE_BANKING_API_KEY);
  strong('fraud.env: MOCK_FRAUD_SCORING_API_KEY', env.fraud.MOCK_FRAUD_SCORING_API_KEY);
  if (env.cbi.MOCK_CORE_BANKING_API_KEY !== env['mock-core-banking'].MOCK_CORE_BANKING_API_KEY) problems.push('MOCK_CORE_BANKING_API_KEY differs between cbi.env and mock-core-banking.env');
  if (env.fraud.MOCK_FRAUD_SCORING_API_KEY !== env['mock-fraud-scoring'].MOCK_FRAUD_SCORING_API_KEY) problems.push('MOCK_FRAUD_SCORING_API_KEY differs between fraud.env and mock-fraud-scoring.env');

  return { problems, keyIds: { serviceToken: tokenKeyId, riskDecision: riskKeyId } };
}

// Reads one setting for setup itself (the Better Auth secret for migrations).
export function readSecret(dir, proc, key) {
  return util.parseEnv(fs.readFileSync(path.join(dir, `${proc}.env`), 'utf8'))[key];
}
