// Per-process secret files (data/secrets/<process>.env), generated independently on each
// computer. Each process loads only its own file (process.loadEnvFile), so a process
// never holds another process's private keys.
//
// Keys:
//   service token  – Ed25519, used with jose (D10). Only the Identity service process
//                    holds the signing key (Step 4B); services hold the public key. The
//                    Next.js "web" process never holds it.
//   risk decision  – Ed25519. Only Fraud & Risk Check signs; the Orchestrator's outbox
//                    worker (Step 6) and Settlement verify (82).
// Paths to certificates are relative to data/.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import util from 'node:util';

import { writeNewFile } from './paths.mjs';

const tls = (name) => ({ TLS_CERT: `pki/${name}.crt`, TLS_KEY: `pki/${name}.key`, TLS_CA: 'pki/ca.crt' });

// Which settings each process receives. Values are filled from generated material.
const SPEC = {
  web: (m) => ({
    BETTER_AUTH_SECRET: m.betterAuthSecret,
    BETTER_AUTH_URL: 'http://localhost:3000',
    // Next.js as a client of Identity and CBI (mTLS, CN=vaultpay-web)
    ...tls('web'),
  }),
  // Step 8: the reconciliation and recovery process (npm run reconcile) – its own read-only
  // client certificate for Identity and CBI. Next.js no longer holds it.
  recon: () => ({
    ...tls('recon'),
  }),
  // The Identity service process: the only holder of the service-token signing key.
  identity: (m) => ({
    SERVICE_TOKEN_SIGNING_KEY: m.token.privateKey,
    SERVICE_TOKEN_KEY_ID: m.token.keyId,
    // Step 7: a settlement token is issued only for a transfer with a valid fraud approval
    RISK_DECISION_PUBLIC_KEY: m.risk.publicKey,
    RISK_DECISION_KEY_ID: m.risk.keyId,
    ...tls('identity'),
  }),
  fraud: (m) => ({
    RISK_DECISION_SIGNING_KEY: m.risk.privateKey,
    RISK_DECISION_KEY_ID: m.risk.keyId,
    SERVICE_TOKEN_PUBLIC_KEY: m.token.publicKey,
    SERVICE_TOKEN_KEY_ID: m.token.keyId,
    MOCK_FRAUD_SCORING_API_KEY: m.fraudScoringApiKey,
    ...tls('fraud'),
  }),
  // The Orchestrator's fraud outbox worker (Step 6): verifies decisions, never signs them.
  orchestrator: (m) => ({
    RISK_DECISION_PUBLIC_KEY: m.risk.publicKey,
    RISK_DECISION_KEY_ID: m.risk.keyId,
    ...tls('orchestrator'),
  }),
  settlement: (m) => ({
    RISK_DECISION_PUBLIC_KEY: m.risk.publicKey,
    RISK_DECISION_KEY_ID: m.risk.keyId,
    SERVICE_TOKEN_PUBLIC_KEY: m.token.publicKey,
    SERVICE_TOKEN_KEY_ID: m.token.keyId,
    ...tls('settlement'), // client of Identity and CBI
    SERVER_TLS_CERT: 'pki/settlement-server.crt', // server for the settlement worker (Step 7)
    SERVER_TLS_KEY: 'pki/settlement-server.key',
  }),
  cbi: (m) => ({
    SERVICE_TOKEN_PUBLIC_KEY: m.token.publicKey,
    SERVICE_TOKEN_KEY_ID: m.token.keyId,
    MOCK_CORE_BANKING_API_KEY: m.coreBankingApiKey,
    ...tls('cbi'),
  }),
  'mock-core-banking': (m) => ({
    MOCK_CORE_BANKING_API_KEY: m.coreBankingApiKey,
    ...tls('mock-core-banking'),
  }),
  'mock-fraud-scoring': (m) => ({
    MOCK_FRAUD_SCORING_API_KEY: m.fraudScoringApiKey,
  }),
};

export const PROCESSES = Object.freeze(Object.keys(SPEC));
export const SECRET_FILES = Object.freeze(PROCESSES.map((p) => `${p}.env`).sort());

const b64 = (buf) => buf.toString('base64url');
const randomSecret = () => b64(crypto.randomBytes(32));

function keyIdFor(prefix, spkiDer) {
  return `${prefix}-${crypto.createHash('sha256').update(spkiDer).digest('hex').slice(0, 16)}`;
}

function ed25519(prefix) {
  const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
  const spki = publicKey.export({ type: 'spki', format: 'der' });
  return {
    privateKey: b64(privateKey.export({ type: 'pkcs8', format: 'der' })),
    publicKey: b64(spki),
    keyId: keyIdFor(prefix, spki),
  };
}

export function generateSecrets(dir, { now = Date.now() } = {}) {
  const material = {
    betterAuthSecret: randomSecret(),
    token: ed25519('st'),
    risk: ed25519('rd'),
    coreBankingApiKey: randomSecret(),
    fraudScoringApiKey: randomSecret(),
  };
  for (const proc of PROCESSES) {
    const values = { VAULTPAY_PROCESS: proc, ...SPEC[proc](material) };
    const body = Object.entries(values).map(([k, v]) => `${k}=${v}`).join('\n');
    writeNewFile(path.join(dir, `${proc}.env`), [
      `# VaultPay ${proc} – generated by npm run setup on ${new Date(now).toISOString()}`,
      '# Local development secrets for THIS computer only. Never commit or copy.',
      body,
      '',
    ].join('\n'));
  }
}

// Loading helpers (also used by the services later).
export const loadPrivateKey = (value) => crypto.createPrivateKey({ key: Buffer.from(value, 'base64url'), format: 'der', type: 'pkcs8' });
export const loadPublicKey = (value) => crypto.createPublicKey({ key: Buffer.from(value, 'base64url'), format: 'der', type: 'spki' });

/**
 * Validates every secret file: exact set of files, exact set of keys per process,
 * keys that load, matching key pairs and key IDs across processes, shared API keys
 * that agree, and certificate paths that stay inside data/pki.
 */
export function verifySecrets(dir) {
  const problems = [];
  let present;
  try {
    present = fs.readdirSync(dir).sort();
  } catch (err) {
    return { problems: [`secrets directory unreadable (${err.code})`], keyIds: {} };
  }
  const missing = SECRET_FILES.filter((f) => !present.includes(f));
  const extra = present.filter((f) => !SECRET_FILES.includes(f));
  if (missing.length) problems.push(`missing: ${missing.join(', ')}`);
  if (extra.length) problems.push(`unexpected files: ${extra.join(', ')}`);
  if (missing.length) return { problems, keyIds: {} };

  // Compare each file's keys against what a fresh generation would produce.
  const placeholder = { token: {}, risk: {} };
  const shape = (proc) => ['VAULTPAY_PROCESS', ...Object.keys(SPEC[proc](placeholder))].sort();
  const env = {};
  for (const proc of PROCESSES) {
    const values = util.parseEnv(fs.readFileSync(path.join(dir, `${proc}.env`), 'utf8'));
    env[proc] = values;
    const keys = Object.keys(values).sort();
    const want = shape(proc);
    const lacking = want.filter((k) => !keys.includes(k));
    const surplus = keys.filter((k) => !want.includes(k));
    if (lacking.length) problems.push(`${proc}.env: missing ${lacking.join(', ')}`);
    if (surplus.length) problems.push(`${proc}.env: must not contain ${surplus.join(', ')}`);
    if (values.VAULTPAY_PROCESS !== proc) problems.push(`${proc}.env: VAULTPAY_PROCESS is "${values.VAULTPAY_PROCESS}"`);
    for (const [k, v] of Object.entries(values)) {
      if (/_TLS_(CERT|KEY)$|^TLS_(CERT|KEY|CA)$/.test(k) && !/^pki\/[a-z-]+\.(crt|key)$/.test(v)) {
        problems.push(`${proc}.env: ${k} must point inside data/pki (got "${v}")`);
      }
    }
  }
  if (problems.length) return { problems, keyIds: {} };

  const pair = (label, signer, signerKey, keyIdName, verifiers, publicName, prefix) => {
    let publicDer;
    try {
      const priv = loadPrivateKey(env[signer][signerKey]);
      if (priv.asymmetricKeyType !== 'ed25519') throw new Error(`is ${priv.asymmetricKeyType}, expected ed25519`);
      publicDer = crypto.createPublicKey(priv).export({ type: 'spki', format: 'der' });
    } catch (err) {
      problems.push(`${signer}.env: ${signerKey} does not load (${err.message})`);
      return undefined;
    }
    const keyId = keyIdFor(prefix, publicDer);
    if (env[signer][keyIdName] !== keyId) problems.push(`${signer}.env: ${keyIdName} does not match its ${label} key`);
    for (const proc of verifiers) {
      try {
        const pub = loadPublicKey(env[proc][publicName]);
        if (!pub.export({ type: 'spki', format: 'der' }).equals(publicDer)) problems.push(`${proc}.env: ${publicName} does not match ${signer}'s ${label} signing key`);
      } catch (err) {
        problems.push(`${proc}.env: ${publicName} does not load (${err.message})`);
      }
      if (env[proc][keyIdName] !== keyId) problems.push(`${proc}.env: ${keyIdName} does not match ${signer}'s ${label} key`);
    }
    return keyId;
  };
  const tokenKeyId = pair('service token', 'identity', 'SERVICE_TOKEN_SIGNING_KEY', 'SERVICE_TOKEN_KEY_ID', ['fraud', 'settlement', 'cbi'], 'SERVICE_TOKEN_PUBLIC_KEY', 'st');
  const riskKeyId = pair('risk decision', 'fraud', 'RISK_DECISION_SIGNING_KEY', 'RISK_DECISION_KEY_ID', ['identity', 'orchestrator', 'settlement'], 'RISK_DECISION_PUBLIC_KEY', 'rd');

  const strong = (label, value) => {
    if (typeof value !== 'string' || Buffer.from(value, 'base64url').length < 32) problems.push(`${label} must be at least 32 random bytes`);
  };
  strong('web.env: BETTER_AUTH_SECRET', env.web.BETTER_AUTH_SECRET);
  strong('cbi.env: MOCK_CORE_BANKING_API_KEY', env.cbi.MOCK_CORE_BANKING_API_KEY);
  strong('fraud.env: MOCK_FRAUD_SCORING_API_KEY', env.fraud.MOCK_FRAUD_SCORING_API_KEY);
  if (env.cbi.MOCK_CORE_BANKING_API_KEY !== env['mock-core-banking'].MOCK_CORE_BANKING_API_KEY) problems.push('MOCK_CORE_BANKING_API_KEY differs between cbi.env and mock-core-banking.env');
  if (env.fraud.MOCK_FRAUD_SCORING_API_KEY !== env['mock-fraud-scoring'].MOCK_FRAUD_SCORING_API_KEY) problems.push('MOCK_FRAUD_SCORING_API_KEY differs between fraud.env and mock-fraud-scoring.env');

  return { problems, keyIds: { serviceToken: tokenKeyId, riskDecision: riskKeyId } };
}

// Reads one setting for setup itself (the Better Auth secret for migrations).
/**
 * Upgrade for an installation created before Step 4B, where web.env held the service-token
 * signing key. Moves that key – unchanged, so nothing has to be re-issued and no TOTP
 * enrollment breaks – into a new identity.env, and rewrites web.env without it (plus its
 * new client-certificate paths). The old web.env is copied to `backupDir` first.
 * Returns true if it upgraded; does nothing for any other layout.
 */
export function upgradeSecretsLayout(dir, { backupDir, now = Date.now() } = {}) {
  const webFile = path.join(dir, 'web.env');
  const identityFile = path.join(dir, 'identity.env');
  if (fs.existsSync(identityFile) || !fs.existsSync(webFile)) return false;
  const old = util.parseEnv(fs.readFileSync(webFile, 'utf8'));
  if (!old.SERVICE_TOKEN_SIGNING_KEY || !old.SERVICE_TOKEN_KEY_ID || !old.BETTER_AUTH_SECRET) return false;
  loadPrivateKey(old.SERVICE_TOKEN_SIGNING_KEY); // must be a usable key before anything moves

  fs.mkdirSync(backupDir, { recursive: true });
  fs.copyFileSync(webFile, path.join(backupDir, 'web.env'), fs.constants.COPYFILE_EXCL);

  const render = (proc, values) => [
    `# VaultPay ${proc} – generated by npm run setup on ${new Date(now).toISOString()} (Step 4B layout upgrade)`,
    '# Local development secrets for THIS computer only. Never commit or copy.',
    // Settings added by later steps (undefined here) are filled in by their own upgrades.
    ...Object.entries({ VAULTPAY_PROCESS: proc, ...values }).filter(([, v]) => v !== undefined).map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n');
  const material = { betterAuthSecret: old.BETTER_AUTH_SECRET, token: { privateKey: old.SERVICE_TOKEN_SIGNING_KEY, keyId: old.SERVICE_TOKEN_KEY_ID }, risk: {} };
  writeNewFile(identityFile, render('identity', SPEC.identity(material)));
  const tmp = `${webFile}.upgrade`;
  writeNewFile(tmp, render('web', SPEC.web(material)));
  fs.renameSync(tmp, webFile);
  return true;
}

/**
 * Upgrade for an installation created before Step 6: gives fraud.env its server-certificate
 * paths and creates orchestrator.env with the risk-decision PUBLIC key derived from
 * fraud.env's signing key (nothing is regenerated). The old fraud.env is backed up first.
 * Returns true if it upgraded; does nothing for any other layout.
 */
export function upgradeSecretsForFraud(dir, { backupDir, now = Date.now() } = {}) {
  const fraudFile = path.join(dir, 'fraud.env');
  const orchestratorFile = path.join(dir, 'orchestrator.env');
  if (fs.existsSync(orchestratorFile) || !fs.existsSync(fraudFile)) return false;
  const fraud = util.parseEnv(fs.readFileSync(fraudFile, 'utf8'));
  if (fraud.VAULTPAY_PROCESS !== 'fraud' || !fraud.RISK_DECISION_SIGNING_KEY || !fraud.RISK_DECISION_KEY_ID || 'TLS_CERT' in fraud) return false;
  const publicKey = crypto.createPublicKey(loadPrivateKey(fraud.RISK_DECISION_SIGNING_KEY)).export({ type: 'spki', format: 'der' });

  fs.mkdirSync(backupDir, { recursive: true });
  fs.copyFileSync(fraudFile, path.join(backupDir, 'fraud.env'), fs.constants.COPYFILE_EXCL);
  const render = (proc, values) => [
    `# VaultPay ${proc} – generated by npm run setup on ${new Date(now).toISOString()} (Step 6 upgrade)`,
    '# Local development secrets for THIS computer only. Never commit or copy.',
    ...Object.entries({ VAULTPAY_PROCESS: proc, ...values }).map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n');
  const fraudValues = { ...fraud };
  delete fraudValues.VAULTPAY_PROCESS;
  writeNewFile(orchestratorFile, render('orchestrator', SPEC.orchestrator({ risk: { publicKey: b64(publicKey), keyId: fraud.RISK_DECISION_KEY_ID } })));
  const tmp = `${fraudFile}.upgrade`;
  writeNewFile(tmp, render('fraud', { ...fraudValues, ...tls('fraud') }));
  fs.renameSync(tmp, fraudFile);
  return true;
}

/**
 * Upgrade for an installation created before Step 7: settlement.env gets its server
 * certificate paths, identity.env the risk-decision PUBLIC key (taken from settlement.env,
 * so nothing is regenerated). Both old files are backed up first. Returns true if it upgraded.
 */
export function upgradeSecretsForSettlement(dir, { backupDir, now = Date.now() } = {}) {
  const files = { settlement: path.join(dir, 'settlement.env'), identity: path.join(dir, 'identity.env') };
  if (!fs.existsSync(files.settlement) || !fs.existsSync(files.identity)) return false;
  const settlement = util.parseEnv(fs.readFileSync(files.settlement, 'utf8'));
  const identity = util.parseEnv(fs.readFileSync(files.identity, 'utf8'));
  const needs = { settlement: !('SERVER_TLS_CERT' in settlement), identity: !('RISK_DECISION_PUBLIC_KEY' in identity) };
  if (!needs.settlement && !needs.identity) return false;
  if (settlement.VAULTPAY_PROCESS !== 'settlement' || identity.VAULTPAY_PROCESS !== 'identity' || !settlement.RISK_DECISION_PUBLIC_KEY || !settlement.RISK_DECISION_KEY_ID) return false;
  loadPublicKey(settlement.RISK_DECISION_PUBLIC_KEY); // must load before anything changes

  fs.mkdirSync(backupDir, { recursive: true });
  for (const proc of Object.keys(files).filter((p) => needs[p])) {
    const backup = path.join(backupDir, `${proc}.env`);
    if (!fs.existsSync(backup)) fs.copyFileSync(files[proc], backup, fs.constants.COPYFILE_EXCL);
  }
  const render = (proc, values) => [
    `# VaultPay ${proc} – generated by npm run setup on ${new Date(now).toISOString()} (Step 7 upgrade)`,
    '# Local development secrets for THIS computer only. Never commit or copy.',
    ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n');
  const write = (proc, values) => {
    const tmp = `${files[proc]}.upgrade`;
    writeNewFile(tmp, render(proc, values));
    fs.renameSync(tmp, files[proc]);
  };
  if (needs.identity) write('identity', { ...identity, RISK_DECISION_PUBLIC_KEY: settlement.RISK_DECISION_PUBLIC_KEY, RISK_DECISION_KEY_ID: settlement.RISK_DECISION_KEY_ID });
  if (needs.settlement) write('settlement', { ...settlement, SERVER_TLS_CERT: 'pki/settlement-server.crt', SERVER_TLS_KEY: 'pki/settlement-server.key' });
  return true;
}

/**
 * Upgrade for an installation created before Step 8: the Reconciliation client certificate
 * paths move from web.env into a new recon.env (the certificate itself is unchanged), so the
 * Next.js process no longer holds a second service identity. Old web.env backed up first.
 */
export function upgradeSecretsForRecon(dir, { backupDir, now = Date.now() } = {}) {
  const webFile = path.join(dir, 'web.env');
  const reconFile = path.join(dir, 'recon.env');
  if (fs.existsSync(reconFile) || !fs.existsSync(webFile)) return false;
  const web = util.parseEnv(fs.readFileSync(webFile, 'utf8'));
  if (web.VAULTPAY_PROCESS !== 'web') return false;
  const hasRecon = Object.keys(web).some((k) => k.startsWith('RECON_'));
  if (hasRecon) {
    fs.mkdirSync(backupDir, { recursive: true });
    const backup = path.join(backupDir, 'web.env');
    if (!fs.existsSync(backup)) fs.copyFileSync(webFile, backup, fs.constants.COPYFILE_EXCL);
  }
  const render = (proc, values) => [
    `# VaultPay ${proc} – generated by npm run setup on ${new Date(now).toISOString()} (Step 8 upgrade)`,
    '# Local development secrets for THIS computer only. Never commit or copy.',
    ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n');
  writeNewFile(reconFile, render('recon', { VAULTPAY_PROCESS: 'recon', ...SPEC.recon() }));
  if (!hasRecon) return true;
  const rest = Object.fromEntries(Object.entries(web).filter(([k]) => !k.startsWith('RECON_')));
  const tmp = `${webFile}.upgrade`;
  writeNewFile(tmp, render('web', rest));
  fs.renameSync(tmp, webFile);
  return true;
}

export function readSecret(dir, proc, key) {
  return util.parseEnv(fs.readFileSync(path.join(dir, `${proc}.env`), 'utf8'))[key];
}
