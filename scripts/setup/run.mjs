// The setup procedure behind `npm run setup`. Exported so tests can run it against a
// temporary data directory.
//
// Rules:
//   - Anything missing is created; anything present is verified and left untouched.
//   - Secrets and certificates are generated as complete sets. A partial set (some files
//     missing) is an error – regenerating only some files would break key pairs/chains.
//   - Replacing existing items needs an explicit flag AND a typed confirmation; the old
//     items are moved to data/backups/<time>/ first, never deleted.

import fs from 'node:fs';
import path from 'node:path';

import { openDatabase } from '../../lib/server/db/index.js';

import { protectDirectory } from './acl.mjs';
import { hasFailures, runChecks } from './check.mjs';
import { DATABASE_NAMES, ensureDatabases } from './databases.mjs';
import { buildDirectoryAtomically, directoryState, ensurePlainDirectory, layout, lstatOrUndefined, SetupError } from './paths.mjs';
import { generatePki, verifyPki } from './pki.mjs';
import { generateSecrets, readSecret, verifySecrets } from './secrets.mjs';
import { assertNotProduction, ensureDemoData } from './seed.mjs';

export const RESETS = Object.freeze({
  db: {
    flag: '--reset-db',
    word: 'RESET',
    description: 'Move all three databases to data/backups/ and create new ones with fresh demo data. All accounts, sessions, transfers and demo balances in this installation are reset.',
  },
  secrets: {
    flag: '--rotate-secrets',
    word: 'ROTATE',
    description: 'Move data/secrets/ to data/backups/ and generate new keys. Existing sessions stop working, and two-factor enrollments encrypted with the old Better Auth secret can no longer be verified.',
  },
  certs: {
    flag: '--renew-certs',
    word: 'RENEW',
    description: 'Move data/pki/ to data/backups/ and issue a new development CA and service certificates.',
  },
});

function acquireLock(lockFile, now) {
  try {
    fs.writeFileSync(lockFile, JSON.stringify({ pid: process.pid, startedAt: new Date(now).toISOString() }), { flag: 'wx' });
  } catch (err) {
    if (err.code !== 'EEXIST') throw err;
    throw new SetupError(`another setup appears to be running (${lockFile} exists). If none is running, delete that file and try again.`);
  }
  return () => fs.rmSync(lockFile, { force: true });
}

// Moves existing items into one timestamped backup folder.
function archive(paths, items, stamp, report) {
  const dest = path.join(paths.backups, stamp);
  fs.mkdirSync(dest, { recursive: true });
  for (const item of items) {
    if (!lstatOrUndefined(item)) continue;
    const target = path.join(dest, path.relative(paths.root, item));
    fs.mkdirSync(path.dirname(target), { recursive: true });
    try {
      fs.renameSync(item, target);
    } catch (err) {
      throw new SetupError(`could not move ${item} to backups (${err.code}). Stop any running VaultPay processes and try again.`);
    }
    report.archived.push(path.relative(paths.root, target));
  }
}

// Ensures a generated directory is either complete-and-valid or absent-then-generated.
async function ensureSet({ label, dir, generate, verify, renewHint, report }) {
  const { state } = directoryState(dir);
  if (state === 'empty') fs.rmdirSync(dir);
  if (state !== 'present') {
    await buildDirectoryAtomically(dir, generate);
    report.created.push(label);
    return;
  }
  const { problems } = verify(dir);
  if (problems.length) {
    throw new SetupError(`${label} exist but are incomplete or invalid: ${problems.join('; ')}. Nothing was changed. To replace them, run npm run setup -- ${renewHint}`);
  }
  report.verified.push(label);
}

function writeManifest(paths, { dataDir, now }) {
  const databases = {};
  for (const name of DATABASE_NAMES) {
    const db = openDatabase(name, { dataDir, readonly: true });
    try {
      const meta = db.prepare('SELECT install_id, schema_version FROM db_meta').get();
      databases[name] = { installId: meta.install_id, schemaVersion: meta.schema_version };
    } finally {
      db.close();
    }
  }
  const manifest = {
    note: 'Generated by npm run setup. Contains no secrets. Never commit data/.',
    databases,
    keyIds: verifySecrets(paths.secrets).keyIds,
    certificates: verifyPki(paths.pki, { now }).certificates,
  };
  const text = `${JSON.stringify(manifest, null, 2)}\n`;
  // Rewritten only when something changed, so a repeat run leaves every file untouched.
  const current = lstatOrUndefined(paths.manifest) ? fs.readFileSync(paths.manifest, 'utf8') : undefined;
  if (current !== text) fs.writeFileSync(paths.manifest, text, { mode: 0o600 });
  return manifest;
}

/**
 * Runs setup. `reset` selects optional replacements ({ db, secrets, certs });
 * `confirm(reset)` must resolve to true for each, or nothing is replaced.
 * Returns a report; throws SetupError (or DbError) on failure.
 */
export async function runSetup({ dataDir, now = Date.now(), reset = {}, confirm = async () => false, repoRoot } = {}) {
  const paths = layout(dataDir);
  const report = { created: [], verified: [], archived: [], warnings: [], checks: [] };
  const stamp = new Date(now).toISOString().replace(/[:.]/g, '-');

  assertNotProduction(); // before anything is created
  ensurePlainDirectory(paths.root);
  const releaseLock = acquireLock(paths.lock, now);
  try {
    const acl = protectDirectory(paths.root);
    report.warnings.push(...acl.problems.map((p) => `permissions: ${p}`));

    const requested = Object.keys(RESETS).filter((k) => reset[k]);
    for (const kind of requested) {
      if (!(await confirm(RESETS[kind]))) throw new SetupError(`${RESETS[kind].flag} was not confirmed; nothing was changed`);
    }
    if (reset.db) archive(paths, DATABASE_NAMES.flatMap((n) => ['', '-wal', '-shm'].map((s) => path.join(paths.db, `${n}.db${s}`))), stamp, report);
    if (reset.secrets) archive(paths, [paths.secrets], stamp, report);
    if (reset.certs) archive(paths, [paths.pki], stamp, report);

    for (const d of [paths.db, paths.backups]) ensurePlainDirectory(d);

    await ensureSet({
      label: 'secrets',
      dir: paths.secrets,
      generate: (dir) => generateSecrets(dir, { now }),
      verify: verifySecrets,
      renewHint: RESETS.secrets.flag,
      report,
    });
    await ensureSet({
      label: 'certificates',
      dir: paths.pki,
      generate: (dir) => generatePki(dir, { now }),
      verify: (dir) => verifyPki(dir, { now }),
      renewHint: RESETS.certs.flag,
      report,
    });

    const authSecret = readSecret(paths.secrets, 'web', 'BETTER_AUTH_SECRET');
    await ensureDatabases({ dataDir, authSecret, now, backupStamp: stamp, report });
    await ensureDemoData({ dataDir, authSecret, now, report });

    report.checks = await runChecks({ dataDir, now, repoRoot });
    if (hasFailures(report.checks)) {
      throw Object.assign(new SetupError('setup finished but the installation check failed'), { checks: report.checks });
    }
    report.manifest = writeManifest(paths, { dataDir, now });
    return report;
  } finally {
    releaseLock();
  }
}
